import { expect, test } from '@playwright/test';
import Database from 'better-sqlite3';

test('live bank, attacker window, SOC, agent authorization, kiosk and recovery work together', async ({ page, context, browser }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const cdp = await context.newCDPSession(page);
  await cdp.send('WebAuthn.enable');
  const authenticator = await cdp.send('WebAuthn.addVirtualAuthenticator', { options: { protocol: 'ctap2', transport: 'internal', hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
  const username = 'live-browser-user';
  await page.goto('/');
  await page.getByRole('button', { name: 'Create account', exact: true }).first().click();
  await page.getByLabel('Username', { exact: true }).fill(username);
  await page.getByRole('button', { name: 'Create account', exact: true }).last().click();
  await expect(page.getByRole('dialog')).toBeVisible();
  const codes = await page.getByRole('dialog').locator('code').allTextContents();
  expect(codes).toHaveLength(8); expect(codes[0]).not.toContain('DEMO');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Continue to sign in' }).click();
  await page.getByLabel('Username', { exact: true }).fill(username);
  const login = page.waitForRequest(request => request.url().endsWith('/api/auth/login-verify'));
  await page.getByRole('button', { name: 'Sign in with a passkey' }).click();
  expect((await login).postDataJSON().dpopPublicKey).toMatchObject({ kty: 'EC', crv: 'P-256' });
  await expect(page.getByRole('heading', { name: `Hello, ${username}` })).toBeVisible();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Admin SOC', exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole('heading', { name: `Hello, ${username}` })).toBeVisible();
  expect((await context.cookies()).some(cookie => cookie.name === 'session_id' && cookie.httpOnly && cookie.secure && cookie.sameSite === 'Strict')).toBe(true);
  const database = new Database(testInfo.config.metadata.databasePath);
  database.prepare("UPDATE users SET role = 'ADMIN' WHERE username = ?").run(username);
  database.close();
  await page.reload();
  await page.getByRole('button', { name: 'Admin SOC', exact: true }).click();
  await expect(page.getByText('No probe run yet.', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Execute live attack runner' }).click();
  await expect(page.locator('.report-counts')).toContainText('PASS: 8', { timeout: 15000 });
  await expect(page.locator('.report-counts')).toContainText('FAIL: 0');
  await page.getByRole('button', { name: 'Verify chain on server' }).click();
  await expect(page.getByText('Server verification: INTACT', { exact: false })).toBeVisible();
  expect(await page.locator('.bounded-feed').evaluate(element => element.clientHeight <= 360)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('live-soc.png'), fullPage: true });

  const attacker = await browser.newContext();
  const attackerPage = await attacker.newPage();
  attackerPage.on('pageerror', error => errors.push(error.message));
  await attackerPage.goto('http://127.0.0.1:3003/phishing');
  await expect(attackerPage.getByRole('heading', { name: 'Phishing and session-replay lab' })).toBeVisible();
  await attackerPage.getByRole('button', { name: 'Submit dummy password' }).click();
  await expect(attackerPage.getByRole('status').filter({ hasText: 'attacker received' })).toBeVisible();
  await attackerPage.getByRole('button', { name: 'Test browser RP isolation' }).click();
  await expect(attackerPage.getByRole('status').filter({ hasText: 'SecurityError' })).toBeVisible();
  await attackerPage.getByRole('button', { name: 'Test server origin verifier' }).click();
  await expect(attackerPage.getByRole('status').filter({ hasText: 'HTTP 401 ORIGIN_MISMATCH' })).toBeVisible();

  await page.getByRole('button', { name: 'Demo arena', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Open phishing lab' })).toBeVisible();
  await page.getByRole('button', { name: 'Run cookie replay comparison' }).click();
  await expect(page.getByText('HTTP 200: your signed request', { exact: false })).toBeVisible();
  await expect(page.getByText('HTTP 401: DPOP_PROOF_REQUIRED', { exact: false })).toBeVisible();
  await expect(attackerPage.locator('.audit-feed')).toContainText('COOKIE REPLAY DEMONSTRATION', { timeout: 10000 });
  await attackerPage.screenshot({ path: testInfo.outputPath('live-attacker.png'), fullPage: true });
  await page.screenshot({ path: testInfo.outputPath('live-demo-arena.png'), fullPage: true });

  await page.getByRole('button', { name: 'AgentShield', exact: true }).click();
  await page.getByRole('button', { name: 'Authorize scope with a passkey' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Server verified the passkey' })).toBeVisible();
  await page.getByRole('button', { name: 'Submit to vulnerable sandbox' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'sandbox accepted' })).toBeVisible();
  await page.getByRole('button', { name: 'Submit to protected gateway' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'HTTP 403' })).toBeVisible();
  await page.getByLabel('Requested recipient').fill('Electricity Board');
  await page.getByLabel('Requested amount (INR)').fill('250');
  await page.getByRole('button', { name: 'Submit to protected gateway' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'HTTP 200: permitted INR 250' })).toBeVisible();

  await page.getByRole('button', { name: 'Crypto Lab', exact: true }).click();
  await page.getByRole('button', { name: 'Run live benchmark' }).click();
  await expect(page.getByRole('table')).toContainText('ML-DSA-44');
  await page.getByRole('button', { name: 'Verify my enrolled passkey' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'server verified your passkey assertion' })).toBeVisible();

  const terminal = await browser.newContext();
  const terminalPage = await terminal.newPage();
  terminalPage.on('pageerror', error => errors.push(error.message));
  await terminalPage.goto('http://localhost:3002/');
  await terminalPage.getByRole('button', { name: 'Use a shared terminal' }).click();
  await expect(terminalPage.getByRole('dialog').getByRole('img')).toBeVisible();
  const approvalUrl = await terminalPage.getByRole('link', { name: 'Open phone approval in another window' }).getAttribute('href');
  await page.goto(approvalUrl!);
  await page.getByLabel('Username', { exact: true }).fill(username);
  await page.getByRole('button', { name: 'Get confirmation code' }).click();
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Approve with a passkey' }).click();
  await expect(page.getByRole('heading', { name: 'Terminal approved' })).toBeVisible();
  await expect(terminalPage.getByRole('heading', { name: `Hello, ${username}` })).toBeVisible({ timeout: 10000 });
  await expect(terminalPage.getByText(/Public terminal ·/)).toBeVisible();
  await expect(terminalPage.getByRole('button', { name: 'Add a passkey' })).toHaveCount(0);
  await terminalPage.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(terminalPage.getByRole('heading', { name: 'Sign in securely' })).toBeVisible();
  await terminal.close();

  await page.goto('/account');
  await cdp.send('WebAuthn.removeVirtualAuthenticator', { authenticatorId: authenticator.authenticatorId });
  await cdp.send('WebAuthn.addVirtualAuthenticator', { options: { protocol: 'ctap2', transport: 'internal', hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
  await page.getByRole('button', { name: 'Add a passkey' }).click();
  await page.getByLabel('Device name').fill('Backup authenticator');
  await page.getByRole('button', { name: 'Enroll passkey', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Revoke Backup authenticator' })).toBeVisible();
  await page.getByRole('button', { name: 'Revoke Backup authenticator' }).click();
  await page.getByRole('button', { name: 'Confirm revocation' }).click();
  await expect(page.getByRole('row').filter({ hasText: 'Backup authenticator' })).toContainText('REVOKED');

  const replacement = await browser.newContext();
  const replacementPage = await replacement.newPage();
  const replacementCdp = await replacement.newCDPSession(replacementPage);
  await replacementCdp.send('WebAuthn.enable');
  await replacementCdp.send('WebAuthn.addVirtualAuthenticator', { options: { protocol: 'ctap2', transport: 'internal', hasResidentKey: true, hasUserVerification: true, isUserVerified: true, automaticPresenceSimulation: true } });
  await replacementPage.goto('http://localhost:3002/recovery');
  await replacementPage.getByLabel('Username', { exact: true }).fill(username);
  await replacementPage.getByLabel('Emergency recovery code').fill(codes[0]);
  await replacementPage.getByRole('button', { name: 'Verify emergency code' }).click();
  await replacementPage.getByRole('dialog').getByRole('button', { name: 'Cancel' }).click();
  await replacementPage.getByLabel('Emergency recovery code').fill(codes[0]);
  await replacementPage.getByRole('button', { name: 'Verify emergency code' }).click();
  await replacementPage.getByRole('button', { name: 'Enroll replacement passkey' }).click();
  await expect(replacementPage.getByRole('heading', { name: 'Your replacement passkey is ready' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Sign in securely' })).toBeVisible();
  await replacementPage.getByRole('button', { name: 'Sign in with your replacement passkey' }).click();
  await replacementPage.getByLabel('Username', { exact: true }).fill(username);
  await replacementPage.getByRole('button', { name: 'Sign in with a passkey' }).click();
  await expect(replacementPage.getByRole('heading', { name: `Hello, ${username}` })).toBeVisible();
  await replacementPage.getByRole('button', { name: 'Admin SOC', exact: true }).click();
  await replacementPage.getByRole('button', { name: 'Active sessions', exact: true }).click();
  await replacementPage.getByRole('button', { name: 'Terminate current session' }).click();
  await replacementPage.getByRole('button', { name: 'Confirm termination' }).click();
  await expect(replacementPage.getByRole('heading', { name: 'Sign in securely' })).toBeVisible();
  await replacement.close(); await attacker.close();
  expect(errors).toEqual([]);
});
