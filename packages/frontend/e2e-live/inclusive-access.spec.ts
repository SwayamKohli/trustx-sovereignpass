import {test,expect} from '@playwright/test';
import Database from 'better-sqlite3';

test('no-phone security-key path, code rotation, changed-browser confirmation and real login history',async({page,context},testInfo)=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  const cdp=await context.newCDPSession(page);await cdp.send('WebAuthn.enable');
  await cdp.send('WebAuthn.addVirtualAuthenticator',{options:{protocol:'ctap2',transport:'usb',hasResidentKey:true,hasUserVerification:true,isUserVerified:true,automaticPresenceSimulation:true}});
  const username='security-key-browser-user';
  await page.goto('/access');
  await expect(page.getByRole('heading',{name:'I have no smartphone',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Register a security key',exact:true}).click();
  await expect(page.getByLabel('Passkey method')).toHaveValue('security-key');
  await page.getByLabel('Username',{exact:true}).fill(username);
  const options=page.waitForResponse(r=>r.url().endsWith('/api/auth/register-challenge')&&r.status()===200);
  await page.getByRole('button',{name:'Create account',exact:true}).last().click();
  expect((await (await options).json()).authenticatorSelection.authenticatorAttachment).toBe('cross-platform');
  await expect(page.getByRole('dialog')).toBeVisible();
  const oldCodes=await page.getByRole('dialog').locator('code').allTextContents();expect(oldCodes).toHaveLength(8);
  await page.getByRole('checkbox').check();await page.getByRole('button',{name:'Continue to sign in'}).click();
  await page.getByLabel('Username',{exact:true}).fill(username);await page.getByRole('button',{name:'Sign in with a passkey'}).click();
  await expect(page.getByRole('heading',{name:`Hello, ${username}`})).toBeVisible();
  await expect(page.getByRole('button',{name:'Record sandbox payment'})).toHaveCount(0);
  await page.screenshot({path:testInfo.outputPath('simple-account.png'),fullPage:true});
  await page.getByRole('button',{name:'Security and recovery',exact:true}).click();
  await expect(page.getByText('Unused recovery codes',{exact:false})).toContainText('8');
  await page.getByRole('button',{name:'Replace recovery codes',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button',{name:'Replace recovery codes',exact:true}).click();
  await page.getByRole('button',{name:'Verify and replace codes',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('All previous recovery codes are now invalid');
  const newCodes=await page.getByRole('dialog').locator('code').allTextContents();expect(newCodes).toHaveLength(8);expect(newCodes).not.toEqual(oldCodes);
  await page.getByRole('checkbox').check();await page.getByRole('button',{name:'Return to account'}).click();
  expect((await context.request.post('http://localhost:3002/api/recovery/verify-code',{data:{username,recoveryCode:oldCodes[0]}})).status()).toBe(400);
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await cdp.send('Network.setUserAgentOverride',{userAgent:'TrustX-authorized-browser-rehearsal'});
  await page.getByLabel('Username',{exact:true}).fill(username);
  const changed=page.waitForResponse(r=>r.url().endsWith('/api/auth/login-verify'));
  await page.getByRole('button',{name:'Sign in with a passkey'}).click();
  const response=await changed;expect(response.status()).toBe(403);expect(response.headers()['set-cookie']).toBeUndefined();
  await expect(page.getByRole('dialog')).toContainText('Browser context changed');
  expect((await context.cookies()).some(c=>c.name==='session_id')).toBe(false);
  await page.getByRole('dialog').getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByRole('button',{name:'Sign in with a passkey'}).click();
  await page.getByRole('button',{name:'Verify this sign-in with my passkey'}).click();
  await expect(page.getByRole('heading',{name:`Hello, ${username}`})).toBeVisible();
  await page.getByRole('button',{name:'Security and recovery',exact:true}).click();
  await expect(page.getByText('A changed context required and completed a fresh passkey check.',{exact:false})).toBeVisible();
  const database=new Database(testInfo.config.metadata.databasePath);database.prepare("UPDATE users SET role='ADMIN' WHERE username=?").run(username);database.close();
  await page.reload();await page.getByRole('button',{name:'Admin SOC',exact:true}).click();
  await page.getByRole('button',{name:'Login history',exact:true}).click();
  await page.getByLabel('Exact username filter').fill(username);await page.getByRole('button',{name:'Apply history filter'}).click();
  await expect(page.getByRole('table')).toContainText('EXTRA_CHECK_REQUIRED');
  await expect(page.getByRole('table')).toContainText('SIGNED_IN');
  await expect(page.getByRole('table')).toContainText('fresh passkey check completed');
  await page.screenshot({path:testInfo.outputPath('login-history.png'),fullPage:true});
  expect(errors).toEqual([]);
});
